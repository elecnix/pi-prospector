/**
 * The decision-model questions of message-origin: who wrote a message the
 * heuristics could not place.
 *
 * Two questions, because they judge two properties. `author` names who wrote the
 * words, and `copied` says whether the person wrote them or sent text they copied
 * from somewhere. Code composes the label: a human author with copied text is
 * `pasted`, with new text `typed`; an agent author is `agent`; a harness author
 * is `notification`. The state is the message alone, cut to its head and tail, so
 * the answer cannot lean on anything the heuristics already used.
 */

import { shortHash, canonicalJson } from "../../input-hash.js";
import { answerOf, type DecisionQuestion, type DecisionResponse } from "../../decision-model.js";
import { MessageOrigin } from "../../message-origin.js";
import { Type, type Static } from "typebox";

/** The characters of a message kept from its start and from its end. */
export const HEAD_CHARS = 1800;
export const TAIL_CHARS = 400;

export const ORIGIN_DECISION_QUESTIONS: Record<string, DecisionQuestion> = {
	author: {
		type: "choice",
		instructions: {
			question: "Who or what wrote the words in `message.text`?",
			focus:
				"Judge the voice and the purpose. A person types to a coding assistant in their own voice, often short and informal. " +
				"An agent writes a brief or a report in a structured, complete style, and refers to the person who owns the work in the third person.",
		},
		criteria: {
			human: {
				what: "A person writing to the assistant: a question, an instruction, a decision, a complaint, a short reply, or text they copied from somewhere",
				not_for: "A brief, report or relayed instruction written by an AI agent for another agent",
				examples: ["why did that fail?", "use the other branch and rerun it", "fuck, you broke the build again"],
			},
			agent: {
				what: "An AI agent or a script writing to another agent: a task brief with sections, a status update, an instruction relayed on someone's behalf, a one-shot test prompt",
				not_for: "A person's own prompt, even a long one",
				examples: [
					"Your task is to review the diff. Report findings as a list. Do not edit files.",
					"The operator approved the plan; proceed with the second step and report back.",
					"Reply with exactly: pong",
				],
			},
			harness: {
				what: "Text generated by a tool or a platform: a monitor event, a notification, a command's output, an error notice, an interruption notice",
				not_for: "Text a person or an agent composed",
				examples: ["CI checks passed on pull request 12", "[Request interrupted by user]", "Exit code 1"],
			},
		},
	},
	copied: {
		type: "noul",
		instructions: {
			question: "Is most of `message.text` material copied from elsewhere, such as a log, a terminal capture, a quoted reply, a web page or a link, rather than newly written words?",
		},
		criteria: {
			true: { what: "Mostly a log, command output, a quoted passage, a page of text or a bare link", examples: ["$ npm test\nPASS 12 tests", "https://example.com/pull/7"] },
			false: { what: "Mostly new sentences written for this conversation, even when they contain a short quote or a link", examples: ["please look at https://example.com/pull/7 and tell me why it fails"] },
		},
	},
};

export const ORIGIN_DECISION_QUESTIONS_HASH = shortHash(`origin-decision(${canonicalJson(ORIGIN_DECISION_QUESTIONS)})`);

/** The state sent for a message: its head and tail when it is long, and a flag that says so. */
export function originDecisionState(text: string): { message: { text: string; shortened: boolean } } {
	const trimmed = text.trim();
	if (trimmed.length <= HEAD_CHARS + TAIL_CHARS) return { message: { text: trimmed, shortened: false } };
	return { message: { text: `${trimmed.slice(0, HEAD_CHARS)}\n[…]\n${trimmed.slice(-TAIL_CHARS)}`, shortened: true } };
}

export const OriginDecision = Type.Object({
	origin: MessageOrigin,
	/** The probability of the weakest of the answers the label rests on. */
	confidence: Type.Number(),
	probabilities: Type.Record(Type.String(), Type.Record(Type.String(), Type.Number())),
});
export type OriginDecision = Static<typeof OriginDecision>;

/** Compose the label from the two answers. */
export function parseOriginDecision(response: DecisionResponse): OriginDecision {
	const author = answerOf(response, "author", "choice");
	const copied = answerOf(response, "copied", "noul");
	const authorP = author.probabilities[author.choice] ?? author.confidence;
	const probabilities = {
		author: author.probabilities,
		copied: { true: copied.noul, false: 1 - copied.noul },
	};
	if (author.choice === "agent") return { origin: "agent", confidence: authorP, probabilities };
	if (author.choice === "harness") return { origin: "notification", confidence: authorP, probabilities };
	const isCopied = copied.noul >= 0.5;
	return { origin: isCopied ? "pasted" : "typed", confidence: Math.min(authorP, isCopied ? copied.noul : 1 - copied.noul), probabilities };
}
